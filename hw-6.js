// Написать функцию, которая принимает целое число и возвращает массив случайных чисел от 0 до этого числа.
// Длина массива должна быть в два раза меньше переданного числа.


function getRandomIntInclusive(min, max) {
    min = Math.ceil(min)
    max = Math.floor(max);
    return Math.floor(Math.random() * (max - min + 1)) + min; // Максимум и минимум включаются
}

   // Основная функция, которая принимает число n 
    function getRandomArray(n) {
    // Проверяем, что передано корректное положительное число 
    if (typeof n !== 'number' || n <= 0) {
        return [];
    }
    // Вычисляем длину массива: в два раза меньше n, округляя вниз
    const length = Math.floor(n / 2);
    // Если результат деления меньше 1 (например, для n=1), возвращаем пустой массив 
    if (length < 1) {
        return [];
    } const result = []; for (let i = 0; i < length; i++) {
        // Генерируем число от 0 до n включительно 
        result.push(getRandomIntInclusive(0, n));
    } 
    return result;
}
// Проверка работы функции 
console.log(getRandomArray(10));
// Пример вывода: [3, 7, 1, 9, 2] (длина 5) 
console.log(getRandomArray(11));
// Пример вывода: [5, 0, 11, 2, 4] (длина 5, так как Math.floor(11/2) = 5)
console.log(getRandomArray(1)); // Вывод: [] (длина 0)
